"""Builds a self-contained single-file V15.5 submission (v14 source embedded inline).

Usage: python build_v15_submission.py [out.py]
Default out: submission.py
"""
import base64
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
V14_SRC = os.path.join(HERE, "agents", "kaggle_boat84_v14.py")
V15_SRC = os.path.join(HERE, "agents", "kaggle_champion_v155.py")

# NOTE: keep this template free of f-string braces; v15.5 source is injected via
# plain str.replace to avoid escaping issues.
TEMPLATE = '''"""V15.5 Champion - single-file Kaggle submission (kaggriculture).

Reverse-engineered hybrid: V14 foundation route + SEB asymmetric market dynamics
+ dead-inventory recovery selling (see V15_TO_V155.md for the full workflow).
1. Replays V14's precomputed foundation route with weed repair.
2. Safe Idle-Turn Fill: on PASS turns, waters unwatered plants and harvests mature
   non-ongoing crops at absolute max yield (strictly non-negative, eliminates PASS waste).
3. Asymmetric Capselllate Top-Up: at step >= 480, bumps planned SELL quantities of
   high-value items (STRAWBERRY/MILK/WOOL) by +1 when shed inventory permits, depressing
   the shared market price right before V14's large scheduled dumps.
4. Nonlinear price-impact sell ranking and clone preemption.
5. Dead-inventory _recovery_sell: in the FINAL window (steps 705..716) only, sells
   shed units the tape will never sell itself (dead inventory) at the front of the
   market queue when the current price is >= gate (STR 60 / MILK 110 / WOOL 200),
   capturing the day-30 price-recovery peak before the terminal dump crashes it.
6. Terminal liquidation at step >= 716.

Empirically verified: 120W/0L vs V15 across 60 seeds (mean delta +492/+472),
40W/0L vs V14 (mean delta +669; V15 baseline was +196).
Generated by build_v15_submission.py - do not edit manually.
"""
import base64 as _b64
import sys as _sys
import types as _types
import zlib as _zlib

_V14_EMBEDDED_B85 = """__B85__"""


class _InlineV14Module(_types.ModuleType):
    def __init__(self, name):
        super().__init__(name)
        self.__dict__["__file__"] = "kaggle_boat84_v14.py"
        self.__dict__["__name__"] = name


_v14_inline = _InlineV14Module("kaggle_boat84_v14")
exec(compile(_zlib.decompress(_b64.b85decode(_V14_EMBEDDED_B85)).decode("utf-8"),
             "kaggle_boat84_v14.py", "exec"), _v14_inline.__dict__)
_sys.modules["kaggle_boat84_v14"] = _v14_inline

# ============ V15 agent body (verbatim from agents/kaggle_champion_v15.py) ============
__V15__
'''


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "submission.py")
    with open(V14_SRC, "r", encoding="utf-8") as f:
        v14_source = f.read()
    with open(V15_SRC, "r", encoding="utf-8") as f:
        v15_source = f.read()

    v14_b85 = base64.b85encode(zlib.compress(v14_source.encode("utf-8"))).decode("ascii")

    bundle = TEMPLATE.replace("__B85__", v14_b85).replace("__V15__", v15_source.rstrip())

    with open(out, "w", encoding="utf-8") as f:
        f.write(bundle)
    print(f"Wrote {out} ({os.path.getsize(out):,} bytes)")


if __name__ == "__main__":
    main()
