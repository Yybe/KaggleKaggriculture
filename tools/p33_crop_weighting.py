"""P33 - IS THE LEADERS' CROP WEIGHTING A ROUTE PROPERTY OR A PER-EPISODE REACTION?

Why this is the last P0-shaped question. `p32` closed the price axis: the seasonal gradient is positive
but unbankable under the shed cap, and the bankable direction (commit before the opponent) is zero-sum.
The remaining non-zero-sum lever on the money side is **which pool the marginal unit enters** - cliffs
CARROT 842 / TOMATO 529 / FERTILIZER 493 vs WOOL 59 / STRAWBERRY 62 / MILK 76 (p18/p19) - which is a
CROP-CHOICE property. p27 measured that carrot is the only item whose price RISES under contest, and that
11/13 leaders run tomato while we ship 0.

That gives two mutually exclusive readings, and they lead to opposite plans:
  (a) ROUTE PROPERTY: a team's crop mix is near-constant across its own episodes and differs across teams
      -> it is generated by the route, so changing it needs route/lineage work (E152, E104 territory) and
      cannot be shipped as a wrapper this cycle.
  (b) PER-EPISODE REACTION: a team varies its mix inside an episode -> it is conditionally responsive to
      the live pool, which IS expressible as a wrapper and would be the first constructible P0 lever.

Test: one-way variance decomposition (ICC) of each crop's tile-day SHARE, within-team vs between-team,
over unique (ep,seat) cells; plus a matched-volume multivariate regression of money on crop shares to ask
whether wide-cliff weighting actually pays at team level.

CONFOUND stated up front, not hidden: teams differ in opponent composition, so the regression is
associational, not causal, and a positive carrot coefficient can be a rich-team marker rather than a
prize. The ICC half of the test is not affected by that confound.

Read-only over results/p6_field_20260925/phase_p6.jsonl + WybeV2/datasets/p6_field_20260925/manifest.csv
(via tools/p19_common). Writes results/p33_crop_weighting/. No engine run, no gate, no agent edited,
no submission mechanism.
"""
from __future__ import annotations

import json
import math
import os
import sys
from collections import defaultdict

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import p19_common as C   # noqa: E402

OUT = os.path.join(C.ROOT, "results", "p33_crop_weighting")
CROPS = ["WHEAT", "CARROT", "TOMATO", "STRAWBERRY", "MELON"]
CLIFF = {"CARROT": 842, "TOMATO": 529, "STRAWBERRY": 62, "MELON": 158, "WHEAT": None}


def canon(t):
    import re
    return re.sub(r"[^\w &]+$", "", (t or "").strip(), flags=re.UNICODE).strip()


def main():
    C.assert_engine_pin()
    join, phase, mi, dup, unmapped = C.build_join()
    rec = []
    for (ep, seat), r in phase.items():
        td = {k: float(v or 0) for k, v in (r.get("tile_days") or {}).items()}
        tot = sum(td.values())
        if tot <= 0:
            continue
        share = {c: td.get(c, 0.0) / tot for c in CROPS}
        an = r.get("end_animals") or {}
        rec.append(dict(team=canon(join.get((ep, seat), "?")), ep=ep, seat=seat, money=float(r.get("money") or 0),
                        tot=tot, na=sum(int(v or 0) for v in an.values()), **share))
    byteam = defaultdict(list)
    for x in rec:
        byteam[x["team"]].append(x)
    groups = {t: g for t, g in byteam.items() if len(g) >= 4}

    L = ["# P33 - crop weighting: route property or per-episode reaction?", "",
         "engine pin %s | unique (ep,seat) cells with tile_days: %d | teams with >=4 episodes: %d"
         % (C.ENGINE_PIN, len(rec), len(groups)), ""]

    # ---------- ICC ----------
    def icc(vals_by_team):
        gs = [np.array(v, dtype=float) for v in vals_by_team if len(v) > 1]
        allv = np.concatenate(gs)
        grand = allv.mean()
        kbar = np.mean([len(g) for g in gs])
        ncap = len(allv)
        msb_num = sum(len(g) * (g.mean() - grand) ** 2 for g in gs)
        msb_den = len(gs) - 1
        msw_num = sum(((g - g.mean()) ** 2).sum() for g in gs)
        msw_den = len(allv) - len(gs)
        msb = msb_num / max(1, msb_den)
        msw = msw_num / max(1, msw_den)
        icc_v = (msb - msw) / (msb + (kbar - 1) * msw) if (msb + (kbar - 1) * msw) else float("nan")
        return icc_v, math.sqrt(msw), msb / msw if msw else float("nan"), ncap

    L += ["## half 1 - variance decomposition of each crop's tile-day SHARE", "",
          "| crop | cliff to $1 | ICC (between-team share of variance) | within-team sd | MSB/MSW | n cells | reading |",
          "|---|---|---:|---:|---:|---:|---|"]
    iccs = {}
    for c in CROPS:
        icc_v, sw, ratio, ncap = icc({t: [x[c] for x in g] for t, g in groups.items()}.values())
        iccs[c] = icc_v
        read = ("ROUTE-fixed" if icc_v > 0.6 else ("mixed" if icc_v > 0.35 else "REACTS within episode"))
        L.append("| %s | %s | **%.3f** | %.3f | %.2f | %d | %s |" % (
            c, CLIFF.get(c) or "log", icc_v, sw, ratio, ncap, read))
    L += ["", "ICC>0.6 means a team's carrot/tomato weighting is essentially a *trait* (route-generated);",
          "ICC<0.35 means the same team swings its mix episode to episode, i.e. it is reacting to something",
          "it can see - and that would be wrapper-expressible.", ""]

    # ---------- our own refs' position ----------
    L += ["## where our own spine sits on the axis (mean share of tile-days)", "",
          "| team | n eps | WHEAT | CARROT | TOMATO | STRAW | MELON | mean tile-days | mean money |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    order = sorted(groups.items(), key=lambda kv: -np.mean([x["money"] for x in kv[1]]))
    for t, g in order:
        star = " **[REF]**" if t in C.REFS else ""
        L.append("| %s%s | %d | %.2f | %.2f | %.2f | %.2f | %.2f | %.0f | %,.0f |".replace(",", "") % (
            t, star, len(g), np.mean([x["WHEAT"] for x in g]), np.mean([x["CARROT"] for x in g]),
            np.mean([x["TOMATO"] for x in g]), np.mean([x["STRAWBERRY"] for x in g]),
            np.mean([x["MELON"] for x in g]), np.mean([x["tot"] for x in g]),
            np.mean([x["money"] for x in g])))

    # ---------- matched-volume regression ----------
    X, y, names = [], [], []
    for x in rec:
        if x["tot"] < 50:
            continue
        X.append([1.0, x["CARROT"], x["TOMATO"], x["MELON"], x["STRAWBERRY"], math.log(max(1.0, x["tot"])), x["na"]])
        y.append(x["money"])
        names.append(x["team"])
    Xa, ya = np.array(X), np.array(y)
    beta, *_ = np.linalg.lstsq(Xa, ya, rcond=None)
    pred = Xa @ beta
    r2 = 1 - ((ya - pred) ** 2).sum() / ((ya - ya.mean()) ** 2).sum()
    resid = ya - pred
    s2 = (resid ** 2).sum() / (len(ya) - Xa.shape[1])
    cov = s2 * np.linalg.pinv(Xa.T @ Xa)
    se = np.sqrt(np.diag(cov))
    L += ["## half 2 - does wide-cliff weighting pay, at matched volume?", "",
          "money ~ 1 + share(CARROT,TOMATO,MELON,STRAWBERRY) + log(tile-days) + n_animals",
          "n=%d seat-episodes, R-squared=%.3f  (STRAWBERRY included; WHEAT is the absorbed category)"
          % (len(ya), r2), "",
          "| term | coefficient (coins per unit of share) | se | t |", "|---|---:|---:|---:|"]
    for nm, b, s in zip(["intercept", "CARROT", "TOMATO", "MELON", "STRAWBERRY", "log tile-days", "n_animals"], beta, se):
        L.append("| %s | %,.0f | %,.0f | %.2f |".replace(",", "") % (nm, b, s, b / s if s else 0))
    L += ["", "**This is associational, not causal**: teams differ in opponent composition, so a positive",
          "carrot coefficient can mark a rich team rather than a prize. Half 1 (ICC) is immune to that",
          "confound and is the part that answers the question asked.", ""]

    # ---------- verdict ----------
    hi = [c for c in CROPS if iccs[c] > 0.6]
    lo = [c for c in CROPS if iccs[c] < 0.35]
    L += ["## VERDICT", "",
          "ICC by crop: " + ", ".join("%s %.3f" % (c, iccs[c]) for c in CROPS), "",
          "Route-fixed (ICC>0.6): %s | Reactive (ICC<0.35): %s | middle: %s" % (
              hi or "none", lo or "none", [c for c in CROPS if 0.35 <= iccs[c] <= 0.6] or "none")]
    txt = "\n".join(L) + "\n"
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "p33_crop_weighting.txt"), "w", encoding="utf-8") as f:
        f.write(txt)
    print(txt)


if __name__ == "__main__":
    main()
